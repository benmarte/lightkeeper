#!/usr/bin/env python3
"""Writes the logo shapes into app/logos.js, from an unpacked Simple Icons package.

    npm pack simple-icons@16.35.0 && tar -xzf simple-icons-16.35.0.tgz
    python3 docs/art/logos.py package

Only the path data is taken: the drawings are CC0, the trademarks stay their owners'.
"""
import json, os, re, sys

SLUGS = ['netflix', 'youtube', 'plex', 'spotify', 'twitch', 'appletv', 'dazn', 'crunchyroll', 'paramountplus',
         'mubi', 'tidal', 'applemusic', 'jellyfin', 'kodi', 'emby', 'vimeo',
         'playstation5', 'playstation4', 'steamdeck', 'nvidia', 'googletv']
pkg = sys.argv[1]
version = json.load(open(os.path.join(pkg, 'package.json')))['version']
shapes = {}
for s in SLUGS:
    svg = open(os.path.join(pkg, 'icons', s + '.svg')).read()
    paths = re.findall(r' d="([^"]+)"', svg)
    assert len(paths) == 1, s
    shapes[s] = paths[0]
block = '// LOGHI:BEGIN generated by docs/art/logos.py from Simple Icons %s\nvar SIMPLE_ICONS = %s;\n// LOGHI:END' % (
    version, json.dumps(shapes, indent=0, sort_keys=True))
target = os.path.join(os.path.dirname(__file__), '..', '..', 'app', 'logos.js')
src = open(target).read()
src = re.sub(r'// LOGHI:BEGIN.*?// LOGHI:END', lambda m: block, src, flags=re.S)
open(target, 'w').write(src)
print('%d logos from Simple Icons %s' % (len(shapes), version))
